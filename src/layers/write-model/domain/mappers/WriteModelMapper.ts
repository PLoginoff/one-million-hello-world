/**
 * WriteModelMapper
 */

export interface WriteModelDto {
  id: string;
  status: string;
  createdAt: string;
  updatedAt: string;
  attributes: Record<string, unknown>;
  tags: string[];
}

export interface WriteModelEntityData {
  id: string;
  status: string;
  createdAt: number;
  updatedAt: number;
  attributes: Record<string, unknown>;
  tags: string[];
}

export class WriteModelMapper {
  toDto(entity: WriteModelEntityData): WriteModelDto {
    return {
      id: entity.id,
      status: entity.status,
      createdAt: new Date(entity.createdAt).toISOString(),
      updatedAt: new Date(entity.updatedAt).toISOString(),
      attributes: { ...entity.attributes },
      tags: [...entity.tags],
    };
  }

  toEntity(dto: WriteModelDto): WriteModelEntityData {
    return {
      id: dto.id,
      status: dto.status,
      createdAt: new Date(dto.createdAt).getTime(),
      updatedAt: new Date(dto.updatedAt).getTime(),
      attributes: { ...dto.attributes },
      tags: [...dto.tags],
    };
  }

  toDtoList(entities: WriteModelEntityData[]): WriteModelDto[] {
    return entities.map((e) => this.toDto(e));
  }

  toEntityList(dtos: WriteModelDto[]): WriteModelEntityData[] {
    return dtos.map((d) => this.toEntity(d));
  }

  merge(base: WriteModelEntityData, patch: Partial<WriteModelEntityData>): WriteModelEntityData {
    return {
      ...base,
      ...patch,
      attributes: { ...base.attributes, ...(patch.attributes ?? {}) },
      tags: patch.tags ? [...patch.tags] : [...base.tags],
    };
  }
}
