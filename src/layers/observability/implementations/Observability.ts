/**
 * Observability Implementation
 *
 * Concrete implementation of IObservability.
 * Handles Metrics, logs and traces aggregation.
 */

import { IObservability } from '../interfaces/IObservability';
import { ObservabilityResult, ObservabilityContext } from '../types/observability-types';

export class Observability implements IObservability {
  private _config: Record<string, unknown>;
  private _metrics: Map<string, number>;

  constructor() {
    this._config = {};
    this._metrics = new Map();
  }

  async execute(context: ObservabilityContext): Promise<ObservabilityResult<unknown>> {
    const startTime = Date.now();
    try {
      const output = this._process(context);
      this._recordMetric('successCount', 1);
      this._recordMetric('lastExecutionTime', Date.now() - startTime);
      return Promise.resolve({ success: true, data: output });
    } catch (error) {
      this._recordMetric('failureCount', 1);
      return Promise.resolve({
        success: false,
        error: {
          code: 'OBSERVABILITY_EXECUTION_ERROR',
          message: error instanceof Error ? error.message : 'Unknown error',
        },
      });
    }
  }

  configure(config: Record<string, unknown>): void {
    this._config = { ...this._config, ...config };
  }

  getStatus(): Record<string, unknown> {
    return {
      config: this._config,
      metrics: Object.fromEntries(this._metrics),
      active: true,
    };
  }

  private _process(context: ObservabilityContext): unknown {
    return { processed: true, context, layer: 'Observability' };
  }

  private _recordMetric(name: string, delta: number): void {
    const current = this._metrics.get(name) ?? 0;
    this._metrics.set(name, current + delta);
  }
}
