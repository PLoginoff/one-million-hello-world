/**
 * PropertyTestingMapper
 */

export interface PropertyTestingDto {
  id: string;
  status: string;
  createdAt: string;
  updatedAt: string;
  attributes: Record<string, unknown>;
  tags: string[];
}

export interface PropertyTestingEntityData {
  id: string;
  status: string;
  createdAt: number;
  updatedAt: number;
  attributes: Record<string, unknown>;
  tags: string[];
}

export class PropertyTestingMapper {
  toDto(entity: PropertyTestingEntityData): PropertyTestingDto {
    return {
      id: entity.id,
      status: entity.status,
      createdAt: new Date(entity.createdAt).toISOString(),
      updatedAt: new Date(entity.updatedAt).toISOString(),
      attributes: { ...entity.attributes },
      tags: [...entity.tags],
    };
  }

  toEntity(dto: PropertyTestingDto): PropertyTestingEntityData {
    return {
      id: dto.id,
      status: dto.status,
      createdAt: new Date(dto.createdAt).getTime(),
      updatedAt: new Date(dto.updatedAt).getTime(),
      attributes: { ...dto.attributes },
      tags: [...dto.tags],
    };
  }

  toDtoList(entities: PropertyTestingEntityData[]): PropertyTestingDto[] {
    return entities.map((e) => this.toDto(e));
  }

  toEntityList(dtos: PropertyTestingDto[]): PropertyTestingEntityData[] {
    return dtos.map((d) => this.toEntity(d));
  }

  merge(base: PropertyTestingEntityData, patch: Partial<PropertyTestingEntityData>): PropertyTestingEntityData {
    return {
      ...base,
      ...patch,
      attributes: { ...base.attributes, ...(patch.attributes ?? {}) },
      tags: patch.tags ? [...patch.tags] : [...base.tags],
    };
  }
}
