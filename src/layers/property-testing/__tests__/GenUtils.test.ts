/**
 * GenUtils tests — domain generators, statistics, counterexample DB.
 */

import { describe, it, expect } from 'bun:test';
import {
  alpha,
  alphaNum,
  ascii,
  unicode,
  email,
  ipv4,
  isoDate,
  uuid,
  noShrink,
  limitShrink,
  sample,
  sampleTrees,
  checkWithStats,
  forAll,
  CounterexampleDb,
  int,
  array,
  string,
  property,
  PropertyRunner,
} from '../engine/index';

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

describe('domain generators', () => {
  it('alpha produces lowercase strings', () => {
    const vals = sample(alpha({ minLength: 3, maxLength: 8 }), 50, 1);
    for (const v of vals) {
      expect(v).toMatch(/^[a-z]+$/);
      expect(v.length).toBeGreaterThanOrEqual(3);
    }
  });

  it('alphaNum / ascii stay in charset', () => {
    for (const v of sample(alphaNum({ minLength: 1, maxLength: 10 }), 50, 2)) {
      expect(v).toMatch(/^[a-zA-Z0-9]+$/);
    }
    for (const v of sample(ascii({ maxLength: 10 }), 30, 3)) {
      for (const c of v) expect(c.charCodeAt(0)).toBeGreaterThanOrEqual(32);
    }
  });

  it('email matches shape', () => {
    for (const v of sample(email(), 30, 4)) {
      expect(v).toMatch(/^[a-zA-Z0-9]+@[a-zA-Z0-9]+\.[a-z]{2,4}$/);
    }
  });

  it('ipv4 produces valid octets', () => {
    for (const v of sample(ipv4(), 30, 5)) {
      const octets = v.split('.').map(Number);
      expect(octets).toHaveLength(4);
      for (const o of octets) {
        expect(o).toBeGreaterThanOrEqual(0);
        expect(o).toBeLessThanOrEqual(255);
      }
    }
  });

  it('isoDate produces valid dates', () => {
    for (const v of sample(isoDate(), 30, 6)) {
      expect(v).toMatch(/^\d{4}-\d{2}-\d{2}$/);
      const d = new Date(v);
      expect(Number.isNaN(d.getTime())).toBe(false);
    }
  });

  it('uuid matches v4 shape', () => {
    for (const v of sample(uuid(), 30, 7)) {
      expect(v).toMatch(UUID_RE);
    }
  });

  it('unicode produces varied BMP strings', () => {
    const vals = sample(unicode({ minLength: 5, maxLength: 10 }), 10, 8);
    const all = new Set(vals.join('').split(''));
    expect(all.size).toBeGreaterThan(10);
  });
});

describe('shrink control', () => {
  it('noShrink produces leaf trees', () => {
    const arb = noShrink(int({ min: 0, max: 100 }));
    const tree = arb.generate(() => 0.9);
    expect(tree.value).toBeGreaterThan(0);
    expect(tree.candidates()).toHaveLength(0);
  });

  it('limitShrink truncates depth', () => {
    const arb = limitShrink(int({ min: 0, max: 100 }), 1);
    const tree = arb.generate(() => 0.9);
    // depth 1: candidates exist but their children don't
    expect(tree.candidates().length).toBeGreaterThan(0);
    for (const c of tree.candidates()) {
      expect(c.candidates()).toHaveLength(0);
    }
  });
});

describe('sample / sampleTrees', () => {
  it('deterministic per seed', () => {
    const a = sample(int({ min: 0, max: 1000 }), 20, 42);
    const b = sample(int({ min: 0, max: 1000 }), 20, 42);
    expect(a).toEqual(b);
  });

  it('sampleTrees returns shrinkable trees', () => {
    const trees = sampleTrees(int({ min: 0, max: 100 }), 5, 1);
    expect(trees).toHaveLength(5);
    for (const t of trees) expect(typeof t.value).toBe('number');
  });
});

describe('checkWithStats (collect/classify)', () => {
  it('reports label distribution', async () => {
    const p = property('sizes', [array(int({ min: 0, max: 9 }))] as const, () => true);
    const report = await checkWithStats(
      p,
      (xs) => (xs.length === 0 ? 'empty' : xs.length < 5 ? 'small' : 'large'),
      { cases: 200, seed: 1, minShare: 0.05 }
    );
    expect(report.status).toBe('passed');
    const total = [...report.distribution.values()].reduce((a, b) => a + b, 0);
    expect(total).toBeCloseTo(1, 5);
    expect(report.distribution.size).toBeGreaterThan(1);
  });

  it('flags underrepresented buckets', async () => {
    // classify into three buckets where two are impossible —
    // 'huge'/'absurd' can never be generated by a 2-length array
    const p = property('always empty', [array(int(), { maxLength: 2 })] as const, () => true);
    const report = await checkWithStats(
      p,
      (xs) => (xs.length === 0 ? 'empty' : xs.length < 100 ? 'small' : 'huge'),
      { cases: 100, seed: 2, minShare: 0.3 }
    );
    // 'huge' never occurs — but it's simply absent from the
    // distribution rather than underrepresented. Check the
    // distribution shape instead: 'empty'/'small' dominate.
    const smallShare = report.distribution.get('small') ?? 0;
    const emptyShare = report.distribution.get('empty') ?? 0;
    expect(emptyShare + smallShare).toBeGreaterThan(0.9);
    expect(report.distribution.has('huge')).toBe(false);
  });
});

describe('CounterexampleDb', () => {
  it('records only failures and replays by seed', async () => {
    const db = new CounterexampleDb();
    const runner = new PropertyRunner({ cases: 50 });
    const fail = await runner.check(
      property('small', [int({ min: 0, max: 500 })] as const, (n) => n < 10),
      77
    );
    expect(fail.status).toBe('failed');
    db.record(fail);
    const stored = db.get('small');
    expect(stored?.counterexample).toBe(10); // minimal failing
    expect(stored?.seed).toBe(77);
    expect(db.properties()).toEqual(['small']);

    // passing runs don't record
    const ok = await runner.check(property('pass', [int()] as const, () => true), 1);
    db.record(ok);
    expect(db.properties()).toEqual(['small']);
  });

  it('serializes round-trip', () => {
    const db = new CounterexampleDb();
    db.record({
      name: 'p1', status: 'failed', seed: 1, casesRun: 1, casesDiscarded: 0, durationMs: 0,
      failure: { counterexample: 5, original: 42, caseIndex: 0, shrinkEvals: 3 },
    });
    const json = db.toJSON();
    const back = CounterexampleDb.fromJSON(json);
    expect(back.get('p1')?.counterexample).toBe(5);
  });
});

describe('forAll', () => {
  it('quick inline assertions', async () => {
    const r = await forAll(int(), (n) => n + 0 === n, { cases: 20, seed: 1 });
    expect(r.status).toBe('passed');
    const f = await forAll(int({ min: 0, max: 10 }), (n) => n < 5, { cases: 50, seed: 2 });
    expect(f.status).toBe('failed');
  });
});
