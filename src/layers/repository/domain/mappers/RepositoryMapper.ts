/**
 * RepositoryMapper
 */

export interface RepositoryDto {
  id: string;
  status: string;
  createdAt: string;
  updatedAt: string;
  attributes: Record<string, unknown>;
  tags: string[];
}

export interface RepositoryEntityData {
  id: string;
  status: string;
  createdAt: number;
  updatedAt: number;
  attributes: Record<string, unknown>;
  tags: string[];
}

export class RepositoryMapper {
  toDto(entity: RepositoryEntityData): RepositoryDto {
    return {
      id: entity.id,
      status: entity.status,
      createdAt: new Date(entity.createdAt).toISOString(),
      updatedAt: new Date(entity.updatedAt).toISOString(),
      attributes: { ...entity.attributes },
      tags: [...entity.tags],
    };
  }

  toEntity(dto: RepositoryDto): RepositoryEntityData {
    return {
      id: dto.id,
      status: dto.status,
      createdAt: new Date(dto.createdAt).getTime(),
      updatedAt: new Date(dto.updatedAt).getTime(),
      attributes: { ...dto.attributes },
      tags: [...dto.tags],
    };
  }

  toDtoList(entities: RepositoryEntityData[]): RepositoryDto[] {
    return entities.map((e) => this.toDto(e));
  }

  toEntityList(dtos: RepositoryDto[]): RepositoryEntityData[] {
    return dtos.map((d) => this.toEntity(d));
  }

  merge(base: RepositoryEntityData, patch: Partial<RepositoryEntityData>): RepositoryEntityData {
    return {
      ...base,
      ...patch,
      attributes: { ...base.attributes, ...(patch.attributes ?? {}) },
      tags: patch.tags ? [...patch.tags] : [...base.tags],
    };
  }
}
