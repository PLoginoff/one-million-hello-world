/**
 * DistributedTracing Entity
 *
 * Core domain entity for the Distributed tracing with OpenTelemetry layer.
 */

export class DistributedTracingEntity {
  readonly id: string;
  readonly createdAt: Date;
  readonly data: Record<string, unknown>;

  constructor(id: string, data: Record<string, unknown>) {
    this.id = id;
    this.createdAt = new Date();
    this.data = { ...data };
  }

  static create(data: Record<string, unknown>): DistributedTracingEntity {
    return new DistributedTracingEntity(
      `distributed-tracing-${Date.now()}-${Math.random().toString(36).substring(2, 8)}`,
      data
    );
  }

  toJSON(): Record<string, unknown> {
    return {
      id: this.id,
      createdAt: this.createdAt.toISOString(),
      data: this.data,
    };
  }
}
