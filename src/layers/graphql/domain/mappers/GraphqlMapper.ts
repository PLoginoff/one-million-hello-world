/**
 * GraphqlMapper
 */

export interface GraphqlDto {
  id: string;
  status: string;
  createdAt: string;
  updatedAt: string;
  attributes: Record<string, unknown>;
  tags: string[];
}

export interface GraphqlEntityData {
  id: string;
  status: string;
  createdAt: number;
  updatedAt: number;
  attributes: Record<string, unknown>;
  tags: string[];
}

export class GraphqlMapper {
  toDto(entity: GraphqlEntityData): GraphqlDto {
    return {
      id: entity.id,
      status: entity.status,
      createdAt: new Date(entity.createdAt).toISOString(),
      updatedAt: new Date(entity.updatedAt).toISOString(),
      attributes: { ...entity.attributes },
      tags: [...entity.tags],
    };
  }

  toEntity(dto: GraphqlDto): GraphqlEntityData {
    return {
      id: dto.id,
      status: dto.status,
      createdAt: new Date(dto.createdAt).getTime(),
      updatedAt: new Date(dto.updatedAt).getTime(),
      attributes: { ...dto.attributes },
      tags: [...dto.tags],
    };
  }

  toDtoList(entities: GraphqlEntityData[]): GraphqlDto[] {
    return entities.map((e) => this.toDto(e));
  }

  toEntityList(dtos: GraphqlDto[]): GraphqlEntityData[] {
    return dtos.map((d) => this.toEntity(d));
  }

  merge(base: GraphqlEntityData, patch: Partial<GraphqlEntityData>): GraphqlEntityData {
    return {
      ...base,
      ...patch,
      attributes: { ...base.attributes, ...(patch.attributes ?? {}) },
      tags: patch.tags ? [...patch.tags] : [...base.tags],
    };
  }
}
