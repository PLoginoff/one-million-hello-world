/**
 * ReadModelMapper
 */

export interface ReadModelDto {
  id: string;
  status: string;
  createdAt: string;
  updatedAt: string;
  attributes: Record<string, unknown>;
  tags: string[];
}

export interface ReadModelEntityData {
  id: string;
  status: string;
  createdAt: number;
  updatedAt: number;
  attributes: Record<string, unknown>;
  tags: string[];
}

export class ReadModelMapper {
  toDto(entity: ReadModelEntityData): ReadModelDto {
    return {
      id: entity.id,
      status: entity.status,
      createdAt: new Date(entity.createdAt).toISOString(),
      updatedAt: new Date(entity.updatedAt).toISOString(),
      attributes: { ...entity.attributes },
      tags: [...entity.tags],
    };
  }

  toEntity(dto: ReadModelDto): ReadModelEntityData {
    return {
      id: dto.id,
      status: dto.status,
      createdAt: new Date(dto.createdAt).getTime(),
      updatedAt: new Date(dto.updatedAt).getTime(),
      attributes: { ...dto.attributes },
      tags: [...dto.tags],
    };
  }

  toDtoList(entities: ReadModelEntityData[]): ReadModelDto[] {
    return entities.map((e) => this.toDto(e));
  }

  toEntityList(dtos: ReadModelDto[]): ReadModelEntityData[] {
    return dtos.map((d) => this.toEntity(d));
  }

  merge(base: ReadModelEntityData, patch: Partial<ReadModelEntityData>): ReadModelEntityData {
    return {
      ...base,
      ...patch,
      attributes: { ...base.attributes, ...(patch.attributes ?? {}) },
      tags: patch.tags ? [...patch.tags] : [...base.tags],
    };
  }
}
