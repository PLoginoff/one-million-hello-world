/**
 * QueryObjectMapper
 */

export interface QueryObjectDto {
  id: string;
  status: string;
  createdAt: string;
  updatedAt: string;
  attributes: Record<string, unknown>;
  tags: string[];
}

export interface QueryObjectEntityData {
  id: string;
  status: string;
  createdAt: number;
  updatedAt: number;
  attributes: Record<string, unknown>;
  tags: string[];
}

export class QueryObjectMapper {
  toDto(entity: QueryObjectEntityData): QueryObjectDto {
    return {
      id: entity.id,
      status: entity.status,
      createdAt: new Date(entity.createdAt).toISOString(),
      updatedAt: new Date(entity.updatedAt).toISOString(),
      attributes: { ...entity.attributes },
      tags: [...entity.tags],
    };
  }

  toEntity(dto: QueryObjectDto): QueryObjectEntityData {
    return {
      id: dto.id,
      status: dto.status,
      createdAt: new Date(dto.createdAt).getTime(),
      updatedAt: new Date(dto.updatedAt).getTime(),
      attributes: { ...dto.attributes },
      tags: [...dto.tags],
    };
  }

  toDtoList(entities: QueryObjectEntityData[]): QueryObjectDto[] {
    return entities.map((e) => this.toDto(e));
  }

  toEntityList(dtos: QueryObjectDto[]): QueryObjectEntityData[] {
    return dtos.map((d) => this.toEntity(d));
  }

  merge(base: QueryObjectEntityData, patch: Partial<QueryObjectEntityData>): QueryObjectEntityData {
    return {
      ...base,
      ...patch,
      attributes: { ...base.attributes, ...(patch.attributes ?? {}) },
      tags: patch.tags ? [...patch.tags] : [...base.tags],
    };
  }
}
