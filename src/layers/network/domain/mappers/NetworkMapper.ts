/**
 * NetworkMapper
 */

export interface NetworkDto {
  id: string;
  status: string;
  createdAt: string;
  updatedAt: string;
  attributes: Record<string, unknown>;
  tags: string[];
}

export interface NetworkEntityData {
  id: string;
  status: string;
  createdAt: number;
  updatedAt: number;
  attributes: Record<string, unknown>;
  tags: string[];
}

export class NetworkMapper {
  toDto(entity: NetworkEntityData): NetworkDto {
    return {
      id: entity.id,
      status: entity.status,
      createdAt: new Date(entity.createdAt).toISOString(),
      updatedAt: new Date(entity.updatedAt).toISOString(),
      attributes: { ...entity.attributes },
      tags: [...entity.tags],
    };
  }

  toEntity(dto: NetworkDto): NetworkEntityData {
    return {
      id: dto.id,
      status: dto.status,
      createdAt: new Date(dto.createdAt).getTime(),
      updatedAt: new Date(dto.updatedAt).getTime(),
      attributes: { ...dto.attributes },
      tags: [...dto.tags],
    };
  }

  toDtoList(entities: NetworkEntityData[]): NetworkDto[] {
    return entities.map((e) => this.toDto(e));
  }

  toEntityList(dtos: NetworkDto[]): NetworkEntityData[] {
    return dtos.map((d) => this.toEntity(d));
  }

  merge(base: NetworkEntityData, patch: Partial<NetworkEntityData>): NetworkEntityData {
    return {
      ...base,
      ...patch,
      attributes: { ...base.attributes, ...(patch.attributes ?? {}) },
      tags: patch.tags ? [...patch.tags] : [...base.tags],
    };
  }
}
