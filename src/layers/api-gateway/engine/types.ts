/**
 * API Gateway Engine — Shared Types
 *
 * Type definitions for the real gateway core: routing, transformation,
 * API key management, rate limiting, logging, circuit breaking,
 * canary routing and response caching.
 *
 * All types are transport-agnostic: headers are treated as
 * case-insensitive multi-maps (name -> string[]).
 *
 * @module ApiGatewayLayer/Engine
 */

/**
 * HTTP-style request entering the gateway.
 *
 * Headers use canonical lower-case names. A header may repeat
 * (e.g. multiple `x-forwarded-for` values), hence the array form.
 */
export interface GatewayRequest {
  /** Unique request id (generated by the caller or the gateway). */
  readonly id: string;
  /** HTTP method, upper-case (GET, POST, ...). */
  readonly method: string;
  /** URL path without query string, e.g. `/api/users/42`. */
  readonly path: string;
  /** Parsed query parameters. */
  readonly query: Record<string, string>;
  /** Request headers (lower-case names). */
  readonly headers: Record<string, string[]>;
  /** Optional request body (already deserialized if applicable). */
  readonly body?: unknown;
  /** Consumer identity if already resolved, else resolved by key auth. */
  consumer?: GatewayConsumer;
  /** Free-form metadata propagated through the pipeline. */
  readonly metadata: Record<string, unknown>;
}

/**
 * Response returned by an upstream service or produced locally.
 */
export interface GatewayResponse {
  /** HTTP status code. */
  readonly status: number;
  /** Response headers (lower-case names). */
  readonly headers: Record<string, string[]>;
  /** Response body. */
  readonly body?: unknown;
  /** Upstream latency in milliseconds. */
  readonly upstreamLatencyMs?: number;
  /** Whether this response came from the gateway cache. */
  readonly cacheHit?: boolean;
}

/**
 * An upstream backend that a route can proxy to.
 */
export interface GatewayUpstream {
  readonly name: string;
  /** Base URL used to build the upstream path, e.g. `http://svc:8080`. */
  readonly baseUrl: string;
  /** Optional weight for weighted load balancing between upstreams. */
  readonly weight?: number;
  /** Canary marker: receives canary-selected traffic only. */
  readonly canary?: boolean;
}

/**
 * Version extraction strategy for a route.
 */
export type VersionSource = 'header' | 'path' | 'query' | 'accept-accept';

/**
 * Declarative API version constraint on a route.
 *
 * `min`/`max` are inclusive semantic-version-ish strings compared
 * component-wise (numeric segments). `exact` wins when provided.
 */
export interface RouteVersionConstraint {
  readonly exact?: string;
  readonly min?: string;
  readonly max?: string;
  /** Header carrying the version, default `x-api-version`. */
  readonly header?: string;
  /** Fallback version when the client sends none. */
  readonly default?: string;
  /** Reject the request when no version is supplied and no default. */
  readonly required?: boolean;
}

/**
 * A compiled route registered in the router.
 *
 * `pathPattern` supports `:param` segments, `{param}` syntax and a
 * trailing `*` wildcard, e.g. `/api/users/:id/orders/*`.
 */
export interface GatewayRoute {
  readonly id: string;
  /** Allowed methods; empty means all. */
  readonly methods: readonly string[];
  /** Path pattern used for matching. */
  readonly pathPattern: string;
  /** Optional version constraint checked against request headers. */
  readonly version?: RouteVersionConstraint;
  /** Ordered upstreams; resolved by canary/weight logic. */
  readonly upstreams: readonly GatewayUpstream[];
  /** Rewrite rules applied to the request before proxying. */
  readonly transforms?: readonly TransformRule[];
  /** Response rewrite rules applied on the way back. */
  readonly responseTransforms?: readonly TransformRule[];
  /** Whether the response may be cached. */
  readonly cacheable?: boolean;
  /** Cache TTL in ms; default engine value otherwise. */
  readonly cacheTtlMs?: number;
  /** Rate limit override for this route. */
  readonly rateLimit?: RateLimitPolicy;
  /** Circuit breaker override for this route. */
  readonly circuit?: CircuitBreakerConfig;
  /** Route priority; higher wins when several routes match. */
  readonly priority?: number;
}

/**
 * Result of a successful route match.
 */
export interface RouteMatch {
  readonly route: GatewayRoute;
  /** Extracted path parameters in declaration order. */
  readonly params: Record<string, string>;
  /** API version resolved from headers/path/query. */
  readonly apiVersion?: string;
  /** Upstream selected by load-balancing/canary logic. */
  readonly upstream: GatewayUpstream;
}

/**
 * A consumer (client application) known to the gateway.
 */
export interface GatewayConsumer {
  readonly id: string;
  readonly name: string;
  /** IDs of currently active API keys. */
  readonly activeKeyIds: readonly string[];
  /** Rate limit policy for this consumer (overrides route default). */
  readonly rateLimit?: RateLimitPolicy;
  /** Consumer group used for canary routing, e.g. `beta`. */
  readonly group?: string;
  readonly attributes?: Record<string, string>;
}

/**
 * Rate limiting policy expressed as token-bucket parameters.
 */
export interface RateLimitPolicy {
  /** Bucket capacity (burst size). */
  readonly burstCapacity: number;
  /** Tokens refilled per second. */
  readonly refillPerSecond: number;
  /** Whether to return a Retry-After hint. */
  readonly emitRetryAfter?: boolean;
}

/**
 * Result of a rate-limit check.
 */
export interface RateLimitDecision {
  readonly allowed: boolean;
  readonly remainingTokens: number;
  readonly retryAfterSeconds?: number;
  /** Policy that produced the decision (route or consumer). */
  readonly source: 'route' | 'consumer';
}

/**
 * Circuit breaker configuration.
 */
export interface CircuitBreakerConfig {
  /** Consecutive failures that trip the breaker open. */
  readonly failureThreshold: number;
  /** How long the breaker stays open before half-open probe (ms). */
  readonly openDurationMs: number;
  /** Probe calls allowed in half-open state. */
  readonly halfOpenMaxCalls: number;
  /** Successes in half-open needed to fully close. */
  readonly halfOpenSuccessThreshold?: number;
}

/**
 * Circuit states: CLOSED -> OPEN -> HALF_OPEN -> CLOSED.
 */
export type CircuitState = 'closed' | 'open' | 'half-open';

/**
 * Transform rule applied to request or response.
 *
 * `target` selects what is rewritten:
 *  - `header:<name>` — set/remove a header
 *  - `query:<name>` — set/remove a query parameter
 *  - `path` — rewrite the matched path
 *
 * For `path`, `value` may reference captured params via `{param}`.
 * When `value` is undefined the target is removed.
 */
export interface TransformRule {
  readonly target: string;
  readonly value?: string;
  /** Apply only when this optional condition matches. */
  readonly when?: TransformCondition;
}

/**
 * Simple equality/regex condition evaluated against the request.
 */
export interface TransformCondition {
  readonly source: 'header' | 'query' | 'param';
  readonly name: string;
  /** Exact string or `/regex/` literal. */
  readonly equals?: string;
  readonly matches?: RegExp;
}

/**
 * Canary routing rule set for the gateway.
 */
export interface CanaryRules {
  /** Consumers in this group always go canary. */
  readonly group?: string;
  /** Percentage of random traffic sent to canary (0-100). */
  readonly weightPercent?: number;
  /** Header that forces canary selection when `value` matches. */
  readonly header?: string;
  readonly headerValue?: string;
}

/**
 * Deterministic clock for time-sensitive components.
 * Injectable so tests can control time without flakiness.
 */
export interface GatewayClock {
  now(): number;
}

/**
 * Real wall-clock implementation.
 */
export class SystemGatewayClock implements GatewayClock {
  now(): number {
    return Date.now();
  }
}

/**
 * Injectable randomness source for canary hashing/selection.
 */
export interface RandomSource {
  /** Next float in [0, 1). */
  next(): number;
}

/**
 * Default math-random source.
 */
export class DefaultRandomSource implements RandomSource {
  next(): number {
    return Math.random();
  }
}
