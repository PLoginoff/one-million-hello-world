/**
 * OnboardingMapper
 */

export interface OnboardingDto {
  id: string;
  status: string;
  createdAt: string;
  updatedAt: string;
  attributes: Record<string, unknown>;
  tags: string[];
}

export interface OnboardingEntityData {
  id: string;
  status: string;
  createdAt: number;
  updatedAt: number;
  attributes: Record<string, unknown>;
  tags: string[];
}

export class OnboardingMapper {
  toDto(entity: OnboardingEntityData): OnboardingDto {
    return {
      id: entity.id,
      status: entity.status,
      createdAt: new Date(entity.createdAt).toISOString(),
      updatedAt: new Date(entity.updatedAt).toISOString(),
      attributes: { ...entity.attributes },
      tags: [...entity.tags],
    };
  }

  toEntity(dto: OnboardingDto): OnboardingEntityData {
    return {
      id: dto.id,
      status: dto.status,
      createdAt: new Date(dto.createdAt).getTime(),
      updatedAt: new Date(dto.updatedAt).getTime(),
      attributes: { ...dto.attributes },
      tags: [...dto.tags],
    };
  }

  toDtoList(entities: OnboardingEntityData[]): OnboardingDto[] {
    return entities.map((e) => this.toDto(e));
  }

  toEntityList(dtos: OnboardingDto[]): OnboardingEntityData[] {
    return dtos.map((d) => this.toEntity(d));
  }

  merge(base: OnboardingEntityData, patch: Partial<OnboardingEntityData>): OnboardingEntityData {
    return {
      ...base,
      ...patch,
      attributes: { ...base.attributes, ...(patch.attributes ?? {}) },
      tags: patch.tags ? [...patch.tags] : [...base.tags],
    };
  }
}
