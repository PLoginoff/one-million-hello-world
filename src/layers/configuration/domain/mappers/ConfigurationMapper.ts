/**
 * ConfigurationMapper
 */

export interface ConfigurationDto {
  id: string;
  status: string;
  createdAt: string;
  updatedAt: string;
  attributes: Record<string, unknown>;
  tags: string[];
}

export interface ConfigurationEntityData {
  id: string;
  status: string;
  createdAt: number;
  updatedAt: number;
  attributes: Record<string, unknown>;
  tags: string[];
}

export class ConfigurationMapper {
  toDto(entity: ConfigurationEntityData): ConfigurationDto {
    return {
      id: entity.id,
      status: entity.status,
      createdAt: new Date(entity.createdAt).toISOString(),
      updatedAt: new Date(entity.updatedAt).toISOString(),
      attributes: { ...entity.attributes },
      tags: [...entity.tags],
    };
  }

  toEntity(dto: ConfigurationDto): ConfigurationEntityData {
    return {
      id: dto.id,
      status: dto.status,
      createdAt: new Date(dto.createdAt).getTime(),
      updatedAt: new Date(dto.updatedAt).getTime(),
      attributes: { ...dto.attributes },
      tags: [...dto.tags],
    };
  }

  toDtoList(entities: ConfigurationEntityData[]): ConfigurationDto[] {
    return entities.map((e) => this.toDto(e));
  }

  toEntityList(dtos: ConfigurationDto[]): ConfigurationEntityData[] {
    return dtos.map((d) => this.toEntity(d));
  }

  merge(base: ConfigurationEntityData, patch: Partial<ConfigurationEntityData>): ConfigurationEntityData {
    return {
      ...base,
      ...patch,
      attributes: { ...base.attributes, ...(patch.attributes ?? {}) },
      tags: patch.tags ? [...patch.tags] : [...base.tags],
    };
  }
}
